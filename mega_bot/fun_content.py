def pick_unique(pool: list[str], recent: list[str] | None = None) -> str:
    """Pick an item avoiding recent ones when possible."""
    recent = recent or []
    candidates = [x for x in pool if x not in recent]
    if not candidates:
        candidates = list(pool)
    return random.choice(candidates)
